const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'data/vocabulary.json'), 'utf8'));
const content = '// Generated by npm run build. Edit data/vocabulary.json instead.\nwindow.IELTS_A1_B1 = ' + JSON.stringify(data, null, 2) + ';\n';
const target = path.join(root, 'vocab-a1-b1-data.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) throw new Error('Run npm run build to update the browser dataset.');
} else {
  fs.writeFileSync(target, content);
  console.log(`Built ${data.entries.length} entries across ${data.topics.length} topics.`);
}
