test('flashcards persist all three statuses and can restart after completion', async ({ page }) => {
  await page.locator('#v-search').fill('student');
  await page.locator('#v-flash-start').click();
  await expect(page.locator('#v-session .v-details')).toBeHidden();
  await page.getByRole('button', { name: 'Hiện nghĩa và ví dụ', exact: true }).click();
  await expect(page.locator('#v-session .v-meaning')).toHaveText('học sinh; sinh viên');
  await page.getByRole('button', { name: 'Đã học →', exact: true }).click();
  await expect(page.locator('#v-session-content')).toContainText('Hoàn thành!');
  await page.getByRole('button', { name: 'Học lại lượt này' }).click();
  await page.getByRole('button', { name: 'Cần ôn tập →' }).click();
  await page.locator('#v-session-close').click();
  await page.reload();
  await page.locator('#nav-vocabulary').click();
  await page.locator('#v-status').selectOption('review');
  await expect(page.locator('.v-card h3')).toHaveText('student');
  await page.getByLabel('Trạng thái của student', { exact: true }).selectOption('new');
  await expect(page.locator('.v-empty')).toBeVisible();
  await expect(page.locator('#v-progress')).toContainText('0/78 đã học');
});
test('quiz locks each answer, marks errors for review and finishes/restarts', async ({ page }) => {
  await page.locator('#v-search').fill('student');
  await page.locator('#v-quiz-start').click();
  const answers = page.locator('.v-answers button');
  await expect(answers).toHaveCount(4);
  await answers.filter({ hasNotText: 'học sinh; sinh viên' }).first().click();
  await expect(page.locator('.v-feedback')).toContainText('Chưa đúng');
  for (const answer of await answers.all()) await expect(answer).toBeDisabled();
  await page.getByRole('button', { name: 'Câu tiếp theo →' }).click();
  await expect(page.locator('#v-session-content')).toContainText('Đúng 0/1');
  await page.getByRole('button', { name: 'Học lại lượt này' }).click();
  await page.getByRole('button', { name: 'học sinh; sinh viên', exact: true }).click();
  await page.getByRole('button', { name: 'Câu tiếp theo →' }).click();
  await expect(page.locator('#v-session-content')).toContainText('Đúng 1/1');
  await page.locator('#v-session-close').click();
  await expect(page.getByLabel('Trạng thái của student', { exact: true })).toHaveValue('review');
});
test('downloads export all filtered entries with source and Vietnamese intact', async ({ page }) => {
  await page.locator('#v-cefr').selectOption('B1');
  const expected = data.entries.filter(w => w.cefr === 'B1');
  let download = page.waitForEvent('download');
  await page.locator('#v-json').click();
  const json = JSON.parse(fs.readFileSync(await (await download).path(), 'utf8'));
  expect(json.entries).toEqual(expected);
  expect(json.sources).toEqual(data.sources);
  download = page.waitForEvent('download');
  await page.locator('#v-csv').click();
  const csv = fs.readFileSync(await (await download).path(), 'utf8');
  expect(csv.startsWith('\uFEFF')).toBeTruthy();
  expect(csv.split('\r\n')).toHaveLength(expected.length + 1);
  expect(csv).toContain('bài tập được giao');
});
test('legacy flashcards and typing survive completion without losing event handlers', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.locator('#nav-home').click();
  await page.locator('.topic-card').first().click();
  await page.locator('#mode-flash').click();
  const count = Number((await page.locator('#flash-counter').textContent()).split('/')[1]);
  // Complete the real legacy topic, then open it again in the same page.
  await page.evaluate(n => { for (let i = 0; i < n; i++) document.getElementById('fc-unknown').click(); }, count);
  await expect(page.locator('#legacy-completion')).toBeVisible();
  await page.getByRole('button', { name: 'Về trang chủ', exact: true }).click();
  await page.locator('#nav-flashcard').click();
  await expect(page.locator('#flash-counter')).toHaveText(`1/${count}`);
  await page.locator('#flash-back').click();
  await page.locator('.topic-card').first().click();
  await page.locator('#mode-type').click();
  await page.locator('#type-input').fill('intentionally-wrong');
  await page.locator('#type-check').click();
  await page.locator('#type-check').click();
  await expect(page.locator('#type-wrong')).toHaveText('1');
  await page.locator('#type-next').click();
  await expect(page.locator('#type-input')).toBeEnabled();
  expect(errors).toEqual([]);
});
test('corrupt saved data and unavailable storage do not prevent learning', async ({ page }) => {
  await page.evaluate(() => { localStorage.setItem('ielts_progress', '{bad'); localStorage.setItem('ielts_a1_b1_progress_v1', '{bad'); });
  await page.reload();
  await page.locator('#nav-vocabulary').click();
  await expect(page.locator('#v-progress')).toContainText('0/78');
  await page.addInitScript(() => {
    Storage.prototype.getItem = () => { throw new Error('blocked'); };
    Storage.prototype.setItem = () => { throw new Error('blocked'); };
  });
  await page.reload();
  await page.locator('#nav-vocabulary').click();
  await expect(page.locator('#v-storage')).toBeVisible();
  await page.getByLabel('Trạng thái của student', { exact: true }).selectOption('learned');
  await expect(page.locator('#v-progress')).toContainText('1/78');
});
